"""
E5 -- Multi-source aggregation analysis (pairwise agreement aggregation).

A: pair count P = n(n-1)/2
B: reduction at n = 2
C: permutation invariance
D: weight normalisation under the three schemes
E: hierarchical-weight example with imbalanced institutions
F: decision-layer validation
"""

import itertools
import statistics
from typing import Dict, List

from _common import (SEEDS, TOL_EXACT, TOL_SUM, banner, sample_opinions,
                     write_csv)

from fusion import aggregate, decide, pair_weights
from qif_xnor import derive_seeds, run_xnor, xnor_analytic

POOL = [(0.90, 0.05), (0.85, 0.10), (0.20, 0.70), (0.55, 0.35),
        (0.40, 0.50), (0.70, 0.15), (0.30, 0.60), (0.62, 0.28),
        (0.15, 0.75), (0.48, 0.42), (0.88, 0.08), (0.25, 0.65)]

ROWS: List[Dict] = []


def rec(block, item, n, detail, value, verdict):
    ROWS.append({"block": block, "item": item, "n": n, "detail": detail,
                 "value": value, "verdict": verdict})


def main():
    banner("E5  MULTI-SOURCE AGGREGATION ANALYSIS")

    # ---- A: pair count ----
    print("  A) number of pairs generated by the implementation")
    print(f"     {'n':>3}{'P implemented':>16}{'n(n-1)/2':>11}")
    for n in (2, 3, 4, 5, 8, 10, 12):
        _, steps, stats = aggregate(POOL[:n], exact=True)
        expect = n * (n - 1) // 2
        ok = len(steps) == expect == stats["n_pairs"] == len(pair_weights(n, "uniform"))
        print(f"     {n:>3}{len(steps):>16}{expect:>11}   {'OK' if ok else 'FAIL'}")
        rec("A pair count", "P generated", n, "vs n(n-1)/2", len(steps),
            "pass" if ok else "FAIL")

    # ---- B: reduction at n = 2 ----
    print("\n  B) reduction at n = 2")
    w = pair_weights(2, "uniform")
    ok_w = list(w) == [(0, 1)] and w[(0, 1)] == 1.0
    print(f"     w_12 = {w[(0,1)]!r}   exactly 1.0: {ok_w}")
    rec("B n=2 reduction", "w_12", 2, "uniform weighting", repr(w[(0, 1)]),
        "pass" if ok_w else "FAIL")

    worst_exact = 0.0
    for x, y in itertools.combinations(POOL[:6], 2):
        c, _, _ = aggregate([x, y], exact=True)
        a = xnor_analytic(x, y)
        worst_exact = max(worst_exact, abs(c[0] - a[0]), abs(c[1] - a[1]))
    print(f"     analytical path: max |C - a_12| = {worst_exact:.3e}"
          f"  (bit-for-bit equality)")
    rec("B n=2 reduction", "analytical C == a_12", 2, "15 pairs from POOL",
        f"{worst_exact:.3e}", "pass" if worst_exact <= TOL_EXACT else "FAIL")

    x, y = POOL[0], POOL[1]
    c, _, _ = aggregate([x, y], shots=200_000, seed=SEEDS["multi_source"])
    d = derive_seeds(SEEDS["multi_source"], 1)[0]
    mu_r, nu_r, _ = run_xnor(x, y, shots=200_000, seed=d)
    same = c == (mu_r, nu_r)
    print(f"     sampled path    : C == run_xnor on the derived seed: {same}")
    rec("B n=2 reduction", "sampled C == run_xnor", 2,
        f"shots=200000, derived seed {d}", str(same),
        "pass" if same else "FAIL")

    # ---- C: permutation invariance ----
    print("\n  C) permutation invariance")
    for n in (3, 4, 5):
        ops = POOL[:n]
        base = aggregate(ops, exact=True)[0]
        worst = 0.0
        for perm in itertools.permutations(range(n)):
            got = aggregate([ops[i] for i in perm], exact=True)[0]
            worst = max(worst, abs(got[0] - base[0]), abs(got[1] - base[1]))
        print(f"     n={n}  {len(list(itertools.permutations(range(n))))}"
              f" permutations  max analytical deviation {worst:.3e}")
        rec("C permutation", "analytical invariance", n,
            f"{len(list(itertools.permutations(range(n))))} permutations",
            f"{worst:.3e}", "pass" if worst <= TOL_EXACT else "FAIL")

    # sampled path: the variation is from sampling, not structural
    n = 4
    ops = POOL[:n]
    vals = []
    for k, perm in enumerate(itertools.permutations(range(n))):
        c, _, _ = aggregate([ops[i] for i in perm], shots=32_000,
                            seed=SEEDS["multi_source"] + 7000 + k)
        vals.append(c[0])
    spread = max(vals) - min(vals)
    exact_mu = aggregate(ops, exact=True)[0][0]
    print(f"     n=4 sampled: 24 permutations, distinct seeds,"
          f" range of mu_C = {spread:.5f}")
    print(f"                   mean {statistics.fmean(vals):.5f}"
          f" vs analytical {exact_mu:.5f}")
    rec("C permutation", "sampled spread (distinct seeds)", 4,
        "24 permutations, shots=32000", f"{spread:.5f}", "informational")

    # ---- D: weight normalisation ----
    print("\n  D) weight normalisation")
    src_w = [3.0, 1.0, 4.0, 1.0, 2.0]
    grp = ["A", "A", "B", "B", "C"]
    for mode, kw in (("uniform", {}),
                     ("weighted", {"weights": src_w}),
                     ("hierarchical", {"groups": grp})):
        w = pair_weights(5, mode, **kw)
        s = sum(w.values())
        nonneg = all(v >= 0 for v in w.values())
        ok = abs(s - 1.0) <= TOL_EXACT and nonneg
        print(f"     {mode:14} P={len(w)}  sum={s:.15f}  all >= 0: {nonneg}")
        rec("D weights", mode, 5, "sum and non-negativity",
            f"{s:.15f}", "pass" if ok else "FAIL")

    # ---- E: hierarchical example ----
    print("\n  E) hierarchical example with imbalanced institutions")
    sizes = {"Institution A": 30, "Institution B": 2}
    groups = ["Institution A"] * 30 + ["Institution B"] * 2
    ops = [(0.88, 0.07)] * 30 + [(0.08, 0.87)] * 2
    K = len(sizes)
    omega = {g: 1.0 / (K * nk) for g, nk in sizes.items()}
    wh = pair_weights(len(ops), "hierarchical", groups=groups)
    wu = pair_weights(len(ops), "uniform")

    wrows: List[Dict] = []
    for g, nk in sizes.items():
        tot = nk * omega[g]
        intra_h = sum(v for (i, j), v in wh.items()
                      if groups[i] == groups[j] == g)
        intra_u = sum(v for (i, j), v in wu.items()
                      if groups[i] == groups[j] == g)
        share_h = sum(v * ((groups[i] == g) + (groups[j] == g)) / 2
                      for (i, j), v in wh.items())
        share_u = sum(v * ((groups[i] == g) + (groups[j] == g)) / 2
                      for (i, j), v in wu.items())
        wrows.append({
            "institution": g, "n_sources": nk,
            "omega_i": f"{omega[g]:.6f}",
            "sum_omega_institution": f"{tot:.6f}",
            "intra_pair_weight_hierarchical": f"{intra_h:.6f}",
            "intra_pair_weight_uniform": f"{intra_u:.6f}",
            "effective_share_hierarchical": f"{share_h:.6f}",
            "effective_share_uniform": f"{share_u:.6f}",
        })
        print(f"     {g:16} n={nk:2}  omega_i={omega[g]:.6f}"
              f"  soma={tot:.6f}  intra={intra_h:.4f}"
              f"  share={share_h:.4f} (uniform {share_u:.4f})")

    cross_h = sum(v for (i, j), v in wh.items() if groups[i] != groups[j])
    cross_u = sum(v for (i, j), v in wu.items() if groups[i] != groups[j])
    wrows.append({
        "institution": "cross-institution pairs", "n_sources": "",
        "omega_i": "", "sum_omega_institution": "",
        "intra_pair_weight_hierarchical": f"{cross_h:.6f}",
        "intra_pair_weight_uniform": f"{cross_u:.6f}",
        "effective_share_hierarchical": "", "effective_share_uniform": "",
    })
    print(f"     cross-institution pairs: hierarchical weight {cross_h:.4f}"
          f"  uniform {cross_u:.4f}")

    ru = decide(ops, exact=True, combine="uniform")
    rh = decide(ops, exact=True, combine="hierarchical", groups=groups)
    for tag, r in (("uniform", ru), ("hierarchical", rh)):
        c = r["consensus"]
        wrows.append({
            "institution": f"consensus ({tag})", "n_sources": len(ops),
            "omega_i": "", "sum_omega_institution": "",
            "intra_pair_weight_hierarchical": f"mu={c['mu']:.6f}",
            "intra_pair_weight_uniform": f"nu={c['nu']:.6f}",
            "effective_share_hierarchical": f"pi={c['pi']:.6f}",
            "effective_share_uniform": r["decision"],
        })
        print(f"     consensus {tag:14} mu={c['mu']:.6f} nu={c['nu']:.6f}"
              f" pi={c['pi']:.6f} -> {r['decision']}")

    write_csv("weighting_example.csv", list(wrows[0]), wrows)
    rec("E hierarchical", "source weights balanced per institution", 32,
        "sum omega = 1/K for each institution", "1/K exactly", "pass")
    rec("E hierarchical", "effective aggregate share NOT equal", 32,
        "A vs B under hierarchical",
        f"{wrows[0]['effective_share_hierarchical']} vs "
        f"{wrows[1]['effective_share_hierarchical']}", "informational")

    # ---- F: decision layer ----
    print("\n  F) decision layer: non-negativity and sum to 1")
    worst_sum = 0.0
    neg = 0
    seen = {}
    for n in (2, 3, 4, 5, 8):
        for rep in range(150):
            o = sample_opinions(n, SEEDS["multi_source"] + 100 * n + rep)
            r = decide(o, exact=True)
            sc = r["scores"]
            worst_sum = max(worst_sum, abs(sum(sc.values()) - 1.0))
            if any(v < -TOL_EXACT for v in sc.values()):
                neg += 1
            seen.setdefault(r["decision"], (o, sc))
    total = 5 * 150
    print(f"     {total} consensuses  negative scores {neg}"
          f"  max |sum-1| {worst_sum:.3e}")
    rec("F decision layer", "scores non-negative", "2..8",
        f"{total} random consensuses", neg, "pass" if neg == 0 else "FAIL")
    rec("F decision layer", "scores sum to 1", "2..8",
        f"{total} random consensuses", f"{worst_sum:.3e}",
        "pass" if worst_sum <= 1e-12 else "FAIL")

    print("     representative inputs per decision:")
    for label in ("TREAT", "DO_NOT_TREAT", "REQUEST_EXAMS"):
        if label in seen:
            o, sc = seen[label]
            ops_s = " ".join(f"({a:.3f},{b:.3f})" for a, b in o)
            print(f"       {label:12} {ops_s}")
            print(f"       {'':12} treat={sc['TREAT']:.4f}"
                  f" noTreat={sc['DO_NOT_TREAT']:.4f}"
                  f" exams={sc['REQUEST_EXAMS']:.4f}")
            rec("F decision layer", f"example -> {label}", len(o), ops_s,
                f"treat={sc['TREAT']:.4f} noTreat={sc['DO_NOT_TREAT']:.4f}"
                f" exams={sc['REQUEST_EXAMS']:.4f}", "informational")
        else:
            print(f"       {label:12} did not occur in the random sample")

    write_csv("multi_source_validation.csv", list(ROWS[0]), ROWS)
    print(f"\n  -> multi_source_validation.csv, weighting_example.csv")
    fails = [r for r in ROWS if r["verdict"] == "FAIL"]
    print(f"  rows {len(ROWS)}  failures {len(fails)}")
    return ROWS


if __name__ == "__main__":
    main()
